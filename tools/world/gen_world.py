def B(*lines):
    build.extend(lines)


def sign(x, z, *text, y=Y, rot=0):
    msgs = [json.dumps(json.dumps({"text": t}))[1:-1] for t in (list(text) + ["", "", "", ""])[:4]]
    inner = ",".join("'" + m.replace("\\\"", "\"").replace("'", "\\'") + "'" for m in msgs)
    B(f"/setblock {x} {y} {z} minecraft:oak_sign[rotation={rot}]{{front_text:{{messages:[{inner}]}}}}")


def thing(cid, kind, what, x, y, z, expect_has, note="", label=None, check_type=None, radius=1.5):
    """Records a check: kind 'block' (inspect block) or 'entity' (inspect entity TYPE X Y Z R)."""
    if kind == "block":
        check.append(f"report CHECK {cid}")
        check.append(f"inspect block {x} {y} {z}")
    else:
        check.append(f"report CHECK {cid}")
        check.append(f"inspect entity {check_type} {x} {y} {z} {radius}")
    expect.append({"id": cid, "kind": kind, "what": what, "at": [x, y, z], "has": expect_has, "note": note})
    layout.append(f"| {cid} | {what} | {x} {y} {z} | {note} |")
    if label:
        sign(x, z + 2 if kind == "block" else z + 2, *label)


def row(title, z, xmin, xmax, sub=""):
    rows.append((title, z, xmin, xmax))
    sign(0, z, title, sub)
    layout.append("")
    layout.append(f"### {title} (z {z})")
    layout.append("")
    layout.append("| check | what | x y z | state |")
    layout.append("|---|---|---|---|")


