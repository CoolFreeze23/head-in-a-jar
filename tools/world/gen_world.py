"""The "one of everything" world: a flat creative world holding one of every block, entity and item of the mod, laid
out in labelled rows, and a check that it is all still there.

  python tools/world/gen_world.py      writes tools/world/world-build.txt, world-check.txt, world-expect.json, LAYOUT.md

world-build.txt (smoke script, @keep baseline_before) builds the world the first time it runs and photographs each row.
world-check.txt opens a copy of the saved world (@keep baseline_check), walks the rows, reads every thing through the
harness's inspect verbs and photographs each row again; check_world.py compares that report with world-expect.json.
check_world.sh does the copy, the run and the comparison in one command.
"""
