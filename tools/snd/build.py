"""Rebuild every Head in a Jar sound made by the recipes in this folder, and the events.json hand-off.

    python tools/snd/build.py                    # every sound, then events.json
    python tools/snd/build.py chair.cut ...      # only these events (events.json is still rewritten in full)
    python tools/snd/build.py --family chair     # only the events whose id starts with chair.
    python tools/snd/build.py --help             # this text; builds nothing

Each take is made from its recipe with seed = 1000 x take + crc32(event id) % 1000, finished to its loudness class
and encoded bit-exact, so a rebuild gives the same bytes. Files go under
src/main/resources/assets/headinajar/sounds/<family>/<name>_<take>.ogg. The nine older files in that folder belong to
tools/make_sounds.py and are never touched here.
"""
import argparse
import json
import os
import sys
import zlib

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from nsynth import finish, export, rng, steps  # noqa: E402
import recipes_feedback, recipes_jar, recipes_chair, recipes_machines  # noqa: E402
import recipes_machines2  # noqa: E402
import recipes_machines3  # noqa: E402
import recipes_machines4  # noqa: E402
import recipes_machines5  # noqa: E402
import recipes_fx  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, '..', '..'))
SOUNDS_DIR = os.path.join(ROOT, 'src', 'main', 'resources', 'assets', 'headinajar', 'sounds')
EVENTS_JSON = os.path.join(HERE, 'events.json')

ALL = recipes_feedback.SOUNDS + recipes_jar.SOUNDS + recipes_chair.SOUNDS + recipes_machines.SOUNDS + recipes_machines2.SOUNDS + recipes_machines3.SOUNDS + recipes_machines4.SOUNDS + recipes_machines5.SOUNDS + recipes_fx.SOUNDS


def seed(sid, take):
    return 1000 * take + zlib.crc32(sid.encode()) % 1000


def files_of(s):
    return [f"{s['file']}_{k}" for k in range(1, s['takes'] + 1)] if s.get('fn') else []


def build_one(s):
    out = []
    for take in range(1, s['takes'] + 1):
        try:
            x = s['fn'](take, rng(seed(s['id'], take)))
        except ValueError as e:
            print(f"{s['id']:28s} take {take}  NOT BUILT: {e}")
            continue
        x = s['finish'](x, s['target']) if s.get('finish') else finish(x, s['target'], fade_out_ms=s['fade_ms'])
        path = os.path.join(SOUNDS_DIR, *f"{s['file']}_{take}.ogg".split('/'))
        export(x, path)
        cuts = steps(x)
        out.append((path, cuts))
        print(f"{s['id']:28s} take {take}  -> {os.path.relpath(path, ROOT)}  hard cuts: {cuts or 'none'}")
    return out


def event_entry(s):
    e = dict(id=f"headinajar:{s['id']}")
    if s.get('fn'):
        e['files'] = [f"headinajar:{f}" for f in files_of(s)]
    if s.get('vanilla'):
        e['vanilla_files'] = s['vanilla']
        e['vanilla_note'] = 'Reference these vanilla sound files by name in sounds.json (nothing is shipped); they follow the player\'s resource pack.'
    for k in ('volume', 'pitch', 'attenuation', 'fixed_range', 'category'):
        e[k] = s[k]
    if s.get('pitch_per_play'):
        e['pitch_per_play'] = s['pitch_per_play']
    e['loudness_class'] = f"{s['cls']} (M max target {s['target']})" if s.get('target') is not None else s.get('cls')
    if s.get('hit_ms') is not None:
        e['hit_ms'] = s['hit_ms']
    e['contact_offset_ticks'] = s.get('preroll_ticks', 0)
    if s.get('loop'):
        e['loop'] = True
    if s.get('ticks'):
        e['chair_ticks'] = s['ticks']
    e['subtitle'] = {'en_us': s['subtitle_en'], 'pt_br': s['subtitle_pt']} if s.get('subtitle_en') else None
    if s.get('clip_key'):
        e['clip_keys'] = s['clip_key']
    e['needs_patient_muffled_version'] = s.get('muffled', False)
    e['how_to_play'] = s['play']
    return e


def write_events():
    events = []
    for s in ALL:
        events.append(event_entry(s))
        if s.get('layer'):
            l = s['layer']
            events.append(dict(id=f"headinajar:{l['id']}", vanilla_files=l['vanilla'], volume=l['volume'],
                               pitch=l['pitch'], attenuation=s['attenuation'], fixed_range=False,
                               category=s['category'], subtitle=None, compound_layer_of=f"headinajar:{s['id']}",
                               needs_patient_muffled_version=False, how_to_play=l['note']))
    doc = dict(
        about='Hand-off from the sound recipes to sounds.json, ModSounds and the lang files. Generated by tools/snd/build.py; edit the recipes, not this file. Nobody has listened to any of these sounds.',
        conventions=dict(
            files='Each entry under "files" is one take: list them all under the event in sounds.json; the game picks one at random per play.',
            volume='Code volume per play. The file carries the loudness; 1.0 is normal. Random volume x0.9-1.0 per play where pitch is randomised.',
            pitch='[low, high] uniform random pitch per play; [1.0, 1.0] means fixed. pitch_per_play overrides it with exact values in order.',
            attenuation='sounds.json attenuation_distance for every take.',
            fixed_range='true: register with SoundEvent.createFixedRangeEvent(id, attenuation) so the server sends it that far.',
            hit_ms='Where the hit (the moment the sound is about) lands in the file.',
            contact_offset_ticks='Start the sound this many ticks BEFORE the contact tick so the hit lands on it (0 = play on the contact tick).',
            chair_ticks='Separation Chair only: the contact ticks t (0-240) of the operation this event is for; the server plays it at t - contact_offset_ticks.',
            subtitle='en_us at most 24 characters, pt_br at most 30; null = compound layer, no subtitle.',
            needs_patient_muffled_version='true: the patient in the chair should hear a muffled version (a later job); until it exists, send the patient the same file.'),
        events=events)
    text = json.dumps(doc, indent=2, ensure_ascii=False) + '\n'
    check_text(text)
    with open(EVENTS_JSON, 'wb') as fh:
        fh.write(text.encode('utf-8'))  # real UTF-8, no BOM: read it with encoding='utf-8', not the system code page
    with open(EVENTS_JSON, 'rb') as fh:
        assert json.loads(fh.read().decode('utf-8')) == doc, 'events.json does not read back as written'
    print('wrote', os.path.relpath(EVENTS_JSON, ROOT), len(events), 'events')


# Text that went through a wrong decode (UTF-8 bytes read as Latin-1 or Windows-1252) shows these.
MOJIBAKE = ('Ã', 'Â', 'â€', '�')


def check_text(text):
    """Fail on mojibake (double-encoded UTF-8) anywhere in the hand-off."""
    for bad in MOJIBAKE:
        if bad in text:
            i = text.index(bad)
            raise SystemExit(f'mojibake {bad!r} near: {text[max(0, i - 40):i + 20]!r}')


def check_recipes():
    ids = [s['id'] for s in ALL]
    assert len(ids) == len(set(ids)), 'duplicate event id'
    for s in ALL:
        if s.get('subtitle_en'):
            assert len(s['subtitle_en']) <= 24 and len(s['subtitle_pt']) <= 30, (s['id'], 'subtitle too long')
            check_text(s['subtitle_en'] + s['subtitle_pt'])


def main(argv):
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('ids', nargs='*', help='event ids to build (default: all)')
    ap.add_argument('--family', help='build only the events whose id starts with FAMILY. (for example chair)')
    a = ap.parse_args(argv)
    check_recipes()
    known = {s['id'] for s in ALL}
    for i in a.ids:
        if i not in known:
            raise SystemExit(f'unknown event id: {i}')
    for s in ALL:
        if not s.get('fn'):
            continue
        if a.ids and s['id'] not in a.ids:
            continue
        if a.family and not s['id'].startswith(a.family + '.'):
            continue
        build_one(s)
    write_events()


if __name__ == '__main__':
    main(sys.argv[1:])
